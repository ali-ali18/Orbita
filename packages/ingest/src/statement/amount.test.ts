import { describe, expect, it } from "vitest";
import { parseAmount } from "./amount.ts";
import { parseStatementDate } from "./date.ts";

describe("parseAmount", () => {
	it.each([
		["1.234,56", 123456],
		["1234,56", 123456],
		["1,234.56", 123456],
		["-12.30", -1230],
		["-12,30", -1230],
		["+12,5", 1250],
		["12", 1200],
		["0,07", 7],
		["R$ 1.234,56", 123456],
		["R$ -12,30", -1230],
		["-R$ 12,30", -1230],
		["(12,30)", -1230],
		["12,30-", -1230],
		["1.234.567,89", 123456789],
		["1.234.567", 123456700],
		["10.00", 1000],
		["19.99", 1999],
		["0.10", 10],
		["0,30", 30],
		["1.005,00", 100500],
		["12,500", null],
		["1.234", null],
		["1,234", null],
		["12,345", null],
		["", null],
		["abc", null],
		["1,2,3", null],
		["12.34,56.78", null],
		["99999999999999,00", null],
		["-0,00", 0],
	])("%s -> %s", (text, cents) => {
		expect(parseAmount(text)).toBe(cents);
	});

	it("nunca passa por float: 0,29 e 1.005,10 saem exatos", () => {
		expect(parseAmount("0,29")).toBe(29);
		expect(parseAmount("1.005,10")).toBe(100510);
		expect(parseAmount("4.35")).toBe(435);
	});

	it("recusa valor acima do limite de centavos", () => {
		expect(parseAmount("21.474.836,48")).toBeNull();
		expect(parseAmount("21.474.836,47")).toBe(2147483647);
	});
});

describe("parseStatementDate", () => {
	it.each([
		["15/03/2026", "2026-03-15"],
		["15-03-2026", "2026-03-15"],
		["15.03.2026", "2026-03-15"],
		["5/3/2026", "2026-03-05"],
		["15/03/26", "2026-03-15"],
		["2026-03-15", "2026-03-15"],
		["2026/03/15", "2026-03-15"],
		["2026-03-15 10:20:00", "2026-03-15"],
		["2026-03-15T10:20:00Z", "2026-03-15"],
		["15/03/2026 10:20", "2026-03-15"],
		["20260315", "2026-03-15"],
		["20260315120000", "2026-03-15"],
		["20260315120000.000[-3:BRT]", "2026-03-15"],
		["31/02/2026", null],
		["03/15/2026", null],
		["2026-13-01", null],
		["", null],
		["hoje", null],
	])("%s -> %s", (text, date) => {
		expect(parseStatementDate(text)).toBe(date);
	});
});
